import re
lines = open("hd_sky.py", encoding="utf-8").read().splitlines()
base_blk = "\n".join(lines[99:145])
base = set(re.findall(r'^\s*"([a-z_0-9]+)"\s*:', base_blk, re.M))
wx = open("hd_weather.py", encoding="utf-8").read()
raw = "".join(re.findall(r'"sky"\s*:\s*\{([^}]*)\}', wx, re.S))
names = set(re.findall(r'"([a-z_0-9]+)"\s*:', raw))
print("BASE keys:", len(base), sorted(base))
print("weather sky keys (%d):" % len(names), sorted(names))
print("UNKNOWN (TypeError):", sorted(names - base))
ps = set(re.findall(r'"sky_preset"\s*:\s*"([a-z_]+)"', wx))
pnames = set(re.findall(r'"([a-z_]+)"', " ".join(lines[326:330])))
print("weather sky_presets:", sorted(ps), "missing:", sorted(ps - pnames))
print("PRESET_NAMES:", sorted(pnames))
