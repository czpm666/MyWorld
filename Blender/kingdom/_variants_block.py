def _row(us, v, z, W=5.1, D=4.8, base=0, dorm=(), faces=None, FH=2.5):
    """Cottage row helper: [(u, v, z, kwargs)]."""
    out = []
    for i, u in enumerate(us):
        d = dict(W=W, D=D, kind=(base + i) % 5, FH=FH)
        if i in dorm:
            d["dorm"] = True
        if faces is not None:
            d["face"] = faces[i]
        out.append((u, v, z, d))
    return out


